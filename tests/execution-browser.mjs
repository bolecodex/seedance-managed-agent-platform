import assert from 'node:assert/strict';
import test from 'node:test';
import path from 'node:path';
import { mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { mockArk, startServer, until } from './helpers/server.js';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.VISIONARY_PLAYWRIGHT_PATH || 'playwright');

test('execution timeline preserves tool details and approvals while keeping the status summary hidden across layouts', async t => {
  const ark = await mockArk(t);
  const { baseUrl } = await startServer(t, { ARK_API_KEY: 'local-test-key', ARK_AGENT_ID: 'test-agent', ARK_ENVIRONMENT_ID: 'test-environment', ARK_BASE_URL: ark.baseUrl });
  const browser = await chromium.launch({ headless: true, ...(process.env.VISIONARY_CHROMIUM_PATH ? { executablePath: process.env.VISIONARY_CHROMIUM_PATH } : {}) });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', cause => errors.push(cause.message));
  await page.route('https://files.test/**', route => route.fulfill({ status: 200, contentType: 'video/mp4', body: '' }));
  await page.goto(baseUrl);
  await until(() => page.locator('#connectionText').textContent().then(text => text.includes('配置就绪')));
  await page.locator('#prompt').fill('为 Sound in Motion 制作一支 15 秒品牌短片，先分析脚本和参考图，再生成分镜与视频。');
  await page.locator('#prompt').press('Enter');
  await until(() => [...ark.sessions.values()][0]?.submissions === 1);
  const session = [...ark.sessions.values()][0];
  assert.equal(await page.locator('#progressBar').count(), 0);
  assert.equal(await page.locator('#progress').isHidden(), true);
  ark.emit(session, { type: 'event_start', event: { id: 'thinking-preview', type: 'agent.thinking' } });
  ark.emit(session, { type: 'event_delta', event_id: 'thinking-preview', delta: { index: 0, content: { type: 'text', text: '先读取故事与分镜，确认 6 张参考图的角色与场景，再按镜头生成画面。' } } });
  const thinking = page.locator('[data-step-id="thinking-preview"]');
  await until(() => thinking.textContent().then(text => text.includes('先读取故事')));
  assert.equal(await thinking.getAttribute('open'), '');
  ark.emit(session, { type: 'agent.thinking', id: 'thinking-preview', content: [{ type: 'text', text: '先读取故事与分镜，确认 6 张参考图的角色与场景，再按镜头生成画面。' }] });
  const plan = ark.emit(session, { type: 'agent.tool_use', name: 'todo_write', input: { todos: [{ content: '分析故事与参考素材', status: 'completed' }, { content: '生成关键帧与镜头', status: 'in_progress' }, { content: '合成并检查成片', status: 'pending' }] } });
  ark.emit(session, { type: 'agent.tool_result', tool_use_id: plan.id, content: [{ type: 'text', text: '执行计划已更新：3 项任务。' }] });
  const tool = ark.emit(session, { type: 'agent.tool_use', name: 'read', input: { file_path: '/mnt/session/storyboard.md' } });
  ark.emit(session, { type: 'agent.tool_result', tool_use_id: tool.id, content: [{ type: 'text', text: '镜头 01：清晨的城市，耳机与脚步同频。\n镜头 02：人物穿过街角，音乐带动画面转场。' }] });
  const detail = page.locator(`[data-step-id="${tool.id}"]`);
  await until(() => detail.locator('.execution-step-status').textContent().then(text => text === '已完成'));
  await detail.locator('summary').click();
  assert.match(await detail.innerText(), /镜头 01/);
  assert.match(await detail.innerText(), /storyboard.md/);
  await detail.locator('summary').focus();
  const mcp = ark.emit(session, { type: 'agent.mcp_tool_use', name: 'lookup_brand', mcp_server_name: 'brand-library', input: { brand: 'Sound in Motion' }, session_thread_id: 'thread-brand-01' });
  ark.emit(session, { type: 'agent.mcp_tool_result', mcp_tool_use_id: mcp.id, content: [{ type: 'text', text: '<img src=x onerror="window.toolXss=true">品牌规范已读取' }] });
  const mcpDetail = page.locator(`[data-step-id="${mcp.id}"]`);
  await until(() => mcpDetail.locator('.execution-step-status').textContent().then(text => text === '已完成'));
  assert.equal(await detail.getAttribute('open'), '');
  assert.equal(await detail.locator('summary').evaluate(element => element === document.activeElement), true);
  await mcpDetail.locator('summary').click();
  assert.match(await mcpDetail.innerText(), /brand-library/);
  assert.match(await mcpDetail.innerText(), /thread-brand-01/);
  assert.equal(await page.evaluate(() => window.toolXss), undefined);
  assert.equal(await mcpDetail.locator('img').count(), 0);
  const failed = ark.emit(session, { type: 'agent.tool_use', name: 'visual_search', input: { query: 'urban headphone campaign' } });
  ark.emit(session, { type: 'agent.tool_result', tool_use_id: failed.id, is_error: true, content: [{ type: 'text', text: '搜索暂不可用，Agent 将使用已有参考图继续。' }] });
  await until(() => page.locator(`[data-step-id="${failed.id}"]`).innerText().then(text => text.includes('搜索暂不可用')));
  const video = ark.emit(session, { type: 'agent.tool_use', name: 'compose_video', input: { output_path: '/mnt/session/outputs/sound-in-motion.mp4' }, evaluated_permission: 'ask' });
  ark.finish(session, false, { text: '参考图与分镜已核对，准备开始生成视频，请确认本次工具调用。', stopReason: 'requires_action', eventIds: [video.id], usage: { input_tokens: 1600, output_tokens: 480 } });
  await until(() => page.locator('#approvalPanel').isVisible());
  assert.equal(await page.locator(`[data-step-id="${video.id}"] .execution-step-status`).textContent(), '等待确认');
  assert.equal(await page.locator('#progress').isHidden(), true);
  assert.match(await page.locator('#executionSession').textContent(), /session-/);
  assert.match(await page.locator('#eventLog').textContent(), /等待工具确认/);
  assert.match(await page.locator('#executionUsage').textContent(), /2,080/);
  const screenshot = process.env.VISIONARY_SCREENSHOT;
  if (screenshot) await mkdir(path.dirname(screenshot), { recursive: true });
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; document.querySelector('#studioScroll').scrollTop = 0; });
  if (screenshot) await page.screenshot({ path: `${screenshot}-execution-desktop.png`, animations: 'disabled' });
  await page.reload();
  await until(() => page.locator(`#messageTimeline [data-step-id="${tool.id}"]`).count());
  assert.equal(await page.locator('#progress').isHidden(), true);
  assert.equal(session.submissions, 1);
  assert.equal(await page.locator('[data-step-id="thinking-preview"]').count(), 1);
  await page.locator('[data-confirm][data-allow="true"]').click();
  await until(() => session.confirmations.length === 1 && session.streams >= 2 && session.ready);
  ark.emit(session, { type: 'agent.tool_result', tool_use_id: video.id, content: [{ type: 'text', text: '视频已生成并保存到 outputs/sound-in-motion.mp4' }] });
  ark.finish(session, false, { text: '已生成短片，成片与分镜均已保存。', usage: { input_tokens: 2400, output_tokens: 920 } });
  await until(() => page.locator('#statusText').textContent().then(text => text === '创作已完成'));
  assert.equal(await page.locator('#progress').isHidden(), true);
  assert.equal(await page.locator(`[data-step-id="${video.id}"] .execution-step-status`).textContent(), '已完成');
  assert.equal(await page.locator('.execution-stages .stage-done').count(), 4);
  assert.match(await page.locator('#executionUsage').textContent(), /3,320/);
  for (const width of [390, 768, 1024]) {
    await page.setViewportSize({ width, height: 844 });
    await page.waitForTimeout(150);
    assert.equal(await page.locator('#progress').isHidden(), true, `status summary stays hidden at ${width}`);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `no page overflow at ${width}`);
    assert.equal(await page.evaluate(() => document.querySelector('#studioScroll').scrollWidth <= document.querySelector('#studioScroll').clientWidth), true, `no timeline overflow at ${width}`);
    if (width === 390 && screenshot) {
      await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; document.querySelector('#studioScroll').scrollTop = 0; });
      await page.screenshot({ path: `${screenshot}-execution-mobile.png`, animations: 'disabled' });
    }
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; document.querySelector('#studioScroll').scrollTop = 0; });
  if (screenshot) await page.screenshot({ path: `${screenshot}-execution-dark.png`, animations: 'disabled' });
  assert.deepEqual(errors, []);
});
