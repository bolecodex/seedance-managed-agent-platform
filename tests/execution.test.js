import assert from 'node:assert/strict';
import test from 'node:test';
import { once } from 'node:events';
import { readFile } from 'node:fs/promises';
import { mockArk, startServer, until } from './helpers/server.js';

const configured = ark => ({ ARK_API_KEY: 'local-test-key', ARK_AGENT_ID: 'test-agent', ARK_ENVIRONMENT_ID: 'test-environment', ARK_BASE_URL: ark.baseUrl });
const inspect = (request, id, condition) => until(async () => { const { task } = await request(`/api/tasks/${id}`); return condition(task) && task; });

test('streams thinking by block index, replaces previews with full events, and correlates builtin and MCP results', async t => {
  const ark = await mockArk(t);
  const { request, dataDir } = await startServer(t, configured(ark));
  const { task } = await request('/api/creative', { prompt: 'Build a product film' });
  await until(() => [...ark.sessions.values()][0]?.submissions === 1);
  const session = [...ark.sessions.values()][0];
  ark.emit(session, { type: 'event_start', event: { type: 'agent.thinking', id: 'thinking-1' } });
  ark.emit(session, { type: 'event_delta', event_id: 'thinking-1', delta: { index: 1, content: { type: 'text', text: 'Second block.' } } });
  ark.emit(session, { type: 'event_delta', event_id: 'thinking-1', delta: { index: 0, content: { type: 'text', text: 'First ' } } });
  ark.emit(session, { type: 'event_delta', event_id: 'thinking-1', delta: { index: 0, content: { type: 'text', text: 'block.' } } });
  let current = await inspect(request, task.id, value => value.streamingPreviews?.[0]?.text === 'First block.\nSecond block.');
  const previewOrder = current.streamingPreviews[0].timelineOrder;
  assert.equal(current.streamingText, '');
  ark.emit(session, { type: 'agent.thinking', id: 'thinking-1', content: [{ type: 'text', text: 'Full planning content.' }] });
  const model = ark.emit(session, { type: 'span.model_request_start' });
  const tool = ark.emit(session, { type: 'agent.tool_use', name: 'video_generate', input: { prompt: 'Sunrise film' }, evaluated_permission: 'allow' });
  const mcp = ark.emit(session, { type: 'agent.mcp_tool_use', name: 'lookup_brand', mcp_server_name: 'brand-library', input: { brand: 'Visionary' }, session_thread_id: 'thread-brand' });
  ark.emit(session, { type: 'agent.mcp_tool_result', mcp_tool_use_id: mcp.id, content: [{ type: 'text', text: 'Brand palette found' }], is_error: false });
  ark.emit(session, { type: 'agent.tool_result', tool_use_id: tool.id, content: [{ type: 'text', text: 'Rendering failed, retry another tool' }], is_error: true });
  ark.emit(session, { type: 'span.model_request_end', model_request_start_id: model.id, model_usage: { input_tokens: 100, output_tokens: 50 } });
  ark.emit(session, { type: 'agent.message', id: 'answer-1', content: [{ type: 'text', text: 'I will revise the film.' }] });
  current = await inspect(request, task.id, value => value.messages.some(item => item.id === 'answer-1'));
  assert.equal(current.streamingPreviews.length, 0);
  const thinking = current.executionSteps.find(item => item.id === 'thinking-1');
  assert.equal(thinking.timelineOrder, previewOrder);
  assert.equal(thinking.text, 'Full planning content.');
  assert.equal(current.executionSteps.filter(item => item.id === tool.id).length, 1);
  assert.equal(current.executionSteps.find(item => item.id === tool.id).status, 'failed');
  const mcpStep = current.executionSteps.find(item => item.id === mcp.id);
  assert.equal(mcpStep.status, 'completed');
  assert.equal(mcpStep.output[0].text, 'Brand palette found');
  assert.equal(mcpStep.threadId, 'thread-brand');
  assert.ok(mcpStep.completedAt);
  assert.equal(current.toolCalls.find(item => item.id === mcp.id).status, 'completed');
  assert.equal(current.executionSteps.find(item => item.id === model.id).usage.output_tokens, 50);
  assert.ok(current.messages[0].timelineOrder < thinking.timelineOrder);
  assert.ok(current.messages.find(item => item.id === 'answer-1').timelineOrder > mcpStep.timelineOrder);
  const saved = JSON.parse(await readFile(`${dataDir}/tasks.json`, 'utf8')).find(item => item.id === task.id);
  assert.equal(saved.executionSteps.find(item => item.id === mcp.id).output[0].text, 'Brand palette found');
  const summary = (await request('/api/tasks')).items.find(item => item.id === task.id);
  for (const key of ['executionSteps', 'streamingPreviews', 'toolCalls']) assert.equal(Object.hasOwn(summary, key), false);
  ark.finish(session);
  await inspect(request, task.id, value => value.status === 'completed');
});

test('reconnect and process restart restore execution history once without resubmitting', async t => {
  const ark = await mockArk(t, { pageSize: 2 });
  const first = await startServer(t, configured(ark));
  const { task } = await first.request('/api/creative', { prompt: 'Recover execution records' });
  await until(() => [...ark.sessions.values()][0]?.submissions === 1);
  const session = [...ark.sessions.values()][0];
  ark.emit(session, { type: 'agent.thinking', id: 'thinking-saved', content: [{ type: 'text', text: 'Saved plan' }] });
  const tool = ark.emit(session, { type: 'agent.tool_use', name: 'read', input: { file_path: '/mnt/session/brief.md' } });
  await inspect(first.request, task.id, value => value.toolCalls?.length === 1);
  session.stream.destroy();
  ark.emit(session, { type: 'agent.tool_result', tool_use_id: tool.id, content: [{ type: 'text', text: 'Recovered brief contents' }] });
  await until(() => session.streams >= 2 && session.ready);
  let current = await inspect(first.request, task.id, value => value.executionSteps?.some(item => item.id === tool.id && item.status === 'completed'));
  const count = current.executionSteps.length;
  const stopped = once(first.child, 'exit'); first.child.kill('SIGKILL'); await stopped;
  const second = await startServer(t, { ...configured(ark), VISIONARY_DATA_DIR: first.dataDir });
  await until(() => session.streams >= 3 && session.ready);
  ark.finish(session, false, { text: 'Recovered answer' });
  current = await inspect(second.request, task.id, value => value.status === 'completed');
  assert.equal(current.executionSteps.length, count);
  assert.equal(current.executionSteps.find(item => item.id === tool.id).output[0].text, 'Recovered brief contents');
  assert.equal(current.executionSteps.filter(item => item.id === 'thinking-saved').length, 1);
  assert.equal(session.submissions, 1);
});

test('permission states and missing tool result content survive confirmation and stay visible', async t => {
  const ark = await mockArk(t);
  const { request } = await startServer(t, configured(ark));
  const { task } = await request('/api/creative', { prompt: 'Load a skill after confirmation' });
  await until(() => [...ark.sessions.values()][0]?.submissions === 1);
  const session = [...ark.sessions.values()][0];
  const tool = ark.emit(session, { type: 'agent.tool_use', name: 'Skill', input: { skill: 'video-producer' }, evaluated_permission: 'ask' });
  ark.finish(session, false, { stopReason: 'requires_action', eventIds: [tool.id] });
  let current = await inspect(request, task.id, value => value.status === 'waiting');
  assert.equal(current.executionSteps.find(item => item.id === tool.id).status, 'waiting');
  await request(`/api/tasks/${task.id}/confirm`, { toolUseId: tool.id, allow: true });
  await until(() => session.streams >= 2 && session.ready);
  ark.emit(session, { type: 'agent.tool_result', tool_use_id: tool.id, is_error: false });
  ark.finish(session);
  current = await inspect(request, task.id, value => value.status === 'completed');
  const skill = current.executionSteps.find(item => item.id === tool.id);
  assert.equal(skill.status, 'completed');
  assert.equal(skill.output, undefined);
  assert.ok(skill.completedAt);
});
